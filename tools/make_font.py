#!/usr/bin/env python3
"""Generate and verify a TFT_eSPI VLW subset; preview the encoded glyphs."""
from pathlib import Path
import argparse
import json
import re
import struct
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SKETCH = ROOT / "firmware/Si4732Traditional"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", required=True)
    args = parser.parse_args()
    source = (SKETCH / "Si4732Traditional.ino").read_text()
    # Remove comments before extracting UI strings, keeping quoted URLs intact.
    token = re.compile(r'"(?:[^"\\]|\\.)*"|//[^\n]*|/\*[\s\S]*?\*/')
    literals = [m.group()[1:-1] for m in token.finditer(source) if m.group().startswith('"')]
    chinese = sorted({c for s in literals for c in s if ord(c) > 127})
    chars = sorted(set(chr(c) for c in range(33, 127)) | set(chinese))
    font = ImageFont.truetype(args.font, 15)
    missing_mask = bytes(font.getmask('\uffff'))
    records, images, resized = [], [], []
    for char in chars:
        box = font.getbbox(char, anchor="ls")
        x0, y0, x1, y1 = box
        mask = Image.new("L", (max(1, x1 - x0), max(1, y1 - y0)))
        ImageDraw.Draw(mask).text((-x0, -y0), char, font=font, fill=255, anchor="ls")
        nonzero = mask.getbbox()
        assert nonzero, f"Empty glyph: {char!r}"
        assert bytes(font.getmask(char)) != missing_mask, f"Missing glyph: {char!r}"
        mask = mask.crop(nonzero)
        if mask.height > 16:
            mask = mask.resize((mask.width, 16), Image.Resampling.LANCZOS)
            resized.append(char)
        x0 += nonzero[0]
        y0 += nonzero[1]
        advance = round(font.getlength(char))
        # A 16-pixel line matches upstream menu row spacing. CJK glyphs use
        # a common top edge; Latin keeps its baseline and descenders.
        dy = max(mask.height - 4, min(12, -y0))
        assert 0 <= 12 - dy and 12 - dy + mask.height <= 16, (char, mask.size, dy)
        records.append((ord(char), mask.height, mask.width, advance, dy, x0, 0))
        images.append(mask)
    blob = struct.pack(">6i", len(chars), 11, 16, 0, 12, 4)
    blob += b"".join(struct.pack(">7i", *r) for r in records)
    blob += b"".join(im.tobytes() for im in images)
    name = b"NotoSansMonoCJKtcSubset"
    blob += struct.pack(">H", len(name)) + name
    blob += struct.pack(">H", len(name)) + name + b"\x01"
    header = "// Generated from Noto Sans Mono CJK TC (SIL OFL 1.1).\n#pragma once\n#include <pgmspace.h>\n\n"
    header += "const uint8_t TraditionalChinese16[] PROGMEM = {\n"
    header += "\n".join("  " + ", ".join(f"0x{b:02X}" for b in blob[i:i+16]) + "," for i in range(0, len(blob), 16))
    header += "\n};\n"
    (SKETCH / "TraditionalChinese16.h").write_text(header)
    assets = ROOT / "assets"
    assets.mkdir(exist_ok=True)
    (assets / "TraditionalChinese16.vlw").write_bytes(blob)
    # Parse the actual generated bytes back, checking all glyph data boundaries.
    decoded = {}
    offset = 24 + 28 * len(chars)
    for i in range(len(chars)):
        cp, h, w, advance, dy, dx, _ = struct.unpack_from(">7i", blob, 24 + i * 28)
        image = Image.frombytes("L", (w, h), blob[offset:offset+w*h])
        decoded[chr(cp)] = (image, advance, dy, dx)
        offset += w*h
    assert offset < len(blob)
    assert set(chinese) <= decoded.keys()
    menu_match = re.search(r'const char \*menu\[\] = \{(.*?)\};', source)
    menu = re.findall(r'"(.*?)"', menu_match.group(1))
    def width(text):
        return sum(decoded[c][1] if c != ' ' else 4 for c in text)
    assert all(width(s) <= 66 for s in menu), [(s, width(s)) for s in menu]
    about_source = source.split("void doabout(", 1)[1].split("spr.unloadFont();", 1)[0]
    about_lines = re.findall(r'spr\.drawString\("([^"]+)",\s*(\d+),\s*(\d+)\);', about_source)
    about_widths = {label: width(label) for label, x, y in about_lines}
    assert about_lines and all(int(x) + about_widths[label] <= 320 for label, x, y in about_lines), about_widths
    # This is a font/layout preview, not a screenshot from the receiver.
    canvas = Image.new("RGB", (700, 260), "#10151d")
    draw = ImageDraw.Draw(canvas)
    def render(text, x, y, color="#ecf4ff"):
        for c in text:
            if c == ' ':
                x += 4
                continue
            im, advance, dy, dx = decoded[c]
            canvas.paste(color, (x+dx, y+12-dy), im)
            x += advance
    render("Si4732 / ESP32-S3", 20, 18)
    render("繁體中文漢化：0.2.1", 230, 18)
    for i, label in enumerate(menu):
        x, y = 20 + (i // 7) * 170, 55 + (i % 7) * 25
        draw.rounded_rectangle((x-3, y-3, x+70, y+18), radius=3, outline="#39526e")
        render(label, x+(64-width(label))//2, y)
    for i, msg in enumerate(["選單", "步進  頻寬  衰減", "搜台  頻率", "載入 SSB 中", "尚未儲存電台", "未偵測到 Si4732", "開啟"]):
        render(msg, 370, 55+i*25)
    render(about_lines[2][0], 370, 230)
    canvas.resize((1400, 520), Image.Resampling.NEAREST).save(assets / "zh-tw-font-preview.png")
    report = {"font": Path(args.font).name, "glyph_count":len(chars), "cjk_glyphs":len(chinese),
              "font_bytes":len(blob), "line_height":16, "missing_glyphs":[], "height_adjusted_glyphs":resized,
              "menu_widths":{s:width(s) for s in menu}, "max_menu_width":66, "about_widths":about_widths,
              "preview":"font/layout preview only; not a hardware screenshot"}
    (assets / "font-validation.json").write_text(json.dumps(report, ensure_ascii=False, indent=2)+"\n")
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    main()
